"""Layer: L2
WP: WP3
Claims: C1, C3, C4
Status: implemented
Requirements: INS-02, INS-21, INS-25

Linear frequency sweep generation from a :class:`~tss.interfaces.SweepSchedule`,
with an optional departure from linearity.

The instrument transmits a linear FMCW sweep and de-chirps the return against
the same reference, which is what INS-21's single-reference architecture means.
Everything L3 does downstream follows from the law implemented here, so the law
is written once, in one place, and both the transmitted waveform and the
de-chirp reference come out of it.

THE LAW
-------
The instantaneous frequency of an ideal linear sweep is

    f(t) = f_start + d * K_f * t

with ``d`` the direction, +1 for an up-sweep and -1 for a down-sweep, and the
phase is its integral,

    phi(t) = 2 pi [ f_start t + d K_f t^2 / 2 ]

The down-sweep is generated by sweeping downward from ``f_stop``, not by
reversing time on an up-sweep, so that a down-sweep starts where an up-sweep
ends and an up/down pair is contiguous in frequency.  That pairing is what C3
uses, so getting it the other way round would make the pair discontinuous and
would put a step in the Doppler estimate at the turn.

WHY NONLINEARITY IS HERE AND NOT AN AFTERTHOUGHT
------------------------------------------------
In a de-chirped FMCW radar a departure from a linear sweep, a sweep rate error
and a Doppler shift all appear as the same thing: a displacement of the beat
frequency, which maps to an apparent range error.  A single sweep cannot tell
them apart.  So a simulator that generates only perfect sweeps cannot be used to
ask whether the processing is robust to any of them, and the answer to whether
C3 works has to survive a sweep that is not exactly linear.

The departure is parameterised by ``nonlinearity_ppm`` on the schedule, as parts
per million of the swept bandwidth.  The shape used is a single parabola that is
zero at both ends of the sweep and peaks at the middle:

    p(s) = 4 s (1 - s),   s = t / T

    f(t) = f_start + d [ K_f t + B eps p(t/T) ]

with ``B`` the swept bandwidth and ``eps = ppm * 1e-6``.  Two properties make
this the right default shape.  It leaves the endpoints exactly where the
schedule says they are, so the swept band is not quietly changed by turning
nonlinearity on.  And a parabola in frequency is a cubic in phase, which is the
lowest-order departure that a linear de-chirp cannot absorb into a range offset,
so it is the first one that actually costs anything.

A real synthesiser's departure is not a single parabola.  This one is a
worst-case-shaped stand-in with a stated peak deviation, which is what a
requirement on sweep linearity can be written against.  Measured phase error
from hardware belongs in a tabulated departure, and
:func:`sweep_frequency_hz` takes one through ``departure_hz`` for exactly that.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping
from typing import Any

import numpy as np

from tss import sweep_law
from tss.interfaces import SweepSchedule

__all__ = [
    "sweep_duration_s",
    "sweep_bandwidth_hz",
    "sweep_time_grid",
    "sweep_frequency_hz",
    "sweep_phase_rad",
    "generate_sweep",
    "beat_frequency_hz",
    "schedule_from_config",
    "validate_schedule",
]


def validate_schedule(sweep: SweepSchedule) -> None:
    """Raise if the schedule is self-contradictory.

    A schedule is a configuration object, so a bad one is a programming or
    configuration error and raising is correct here.  Contract rule 3 is about
    physical impossibility in a result, not about a sweep rate of zero.
    """
    if sweep.k_f_hz_per_s <= 0.0:
        raise ValueError("k_f_hz_per_s must be positive; direction sets the sign")
    if sweep.f_stop_hz <= sweep.f_start_hz:
        raise ValueError(
            "f_stop_hz must be above f_start_hz; a down-sweep is direction=-1 over "
            "the same band, not a reversed band"
        )
    if sweep.direction not in (1, -1):
        raise ValueError(f"direction must be +1 or -1, got {sweep.direction!r}")
    if sweep.sweep_period_s <= 0.0:
        raise ValueError("sweep_period_s must be positive")
    if sweep_law.is_stepped(sweep):
        sweep_law.validate_stepped(sweep)


def sweep_bandwidth_hz(sweep: SweepSchedule) -> float:
    """Swept bandwidth, ``f_stop - f_start``."""
    return float(sweep.f_stop_hz) - float(sweep.f_start_hz)


def sweep_duration_s(sweep: SweepSchedule) -> float:
    """Time to cross the band at the scheduled rate, ``B / K_f``.

    This is the active sweep time and it can be shorter than
    ``sweep_period_s``, which includes whatever retrace or dead time the
    schedule allows.  The duration used for synthesis is this one, because
    transmitting during retrace is not what the instrument does.

    For a stepped schedule it is ``n_steps * step_dwell_s``.
    """
    if sweep_law.is_stepped(sweep):
        return sweep_law.active_duration_s(sweep)
    return sweep_bandwidth_hz(sweep) / float(sweep.k_f_hz_per_s)


def sweep_time_grid(sweep: SweepSchedule, fs_hz: float, n_samples: int | None = None) -> np.ndarray:
    """Sample times through one sweep, seconds from the start of the sweep."""
    if fs_hz <= 0.0:
        raise ValueError("fs_hz must be positive")
    if n_samples is None:
        n_samples = int(np.floor(sweep_duration_s(sweep) * float(fs_hz)))
    n_samples = int(n_samples)
    if n_samples < 2:
        raise ValueError(
            f"a sweep needs at least two samples; fs={fs_hz:g} Hz over "
            f"{sweep_duration_s(sweep):g} s gives {n_samples}"
        )
    return np.arange(n_samples, dtype=float) / float(fs_hz)


def _parabolic_departure(t: np.ndarray, duration_s: float) -> np.ndarray:
    """``p(s) = 4 s (1 - s)`` with ``s = t / T``, clipped outside the sweep."""
    s = np.clip(np.asarray(t, dtype=float) / float(duration_s), 0.0, 1.0)
    return 4.0 * s * (1.0 - s)


def _parabolic_departure_integral(t: np.ndarray, duration_s: float) -> np.ndarray:
    """Integral of :func:`_parabolic_departure` with respect to ``t``.

    ``int_0^t 4 s (1-s) dt = 4 T [ s^2/2 - s^3/3 ]``.  Used for the phase, which
    has to be the exact integral of the frequency law rather than a numerical
    one, otherwise the de-chirp reference and the transmitted waveform carry
    different accumulated phase and the residual looks like an impairment that
    is not there.
    """
    duration = float(duration_s)
    s = np.clip(np.asarray(t, dtype=float) / duration, 0.0, 1.0)
    return 4.0 * duration * (s**2 / 2.0 - s**3 / 3.0)


def sweep_frequency_hz(
    sweep: SweepSchedule,
    t: np.ndarray | float,
    *,
    departure_hz: Callable[[np.ndarray], np.ndarray] | None = None,
) -> np.ndarray:
    """Instantaneous transmit frequency at times ``t``, Hz.

    ``t`` is measured from the start of the sweep.  For a down-sweep the law
    starts at ``f_stop_hz`` and descends, so that an up-sweep and the down-sweep
    that follows it are contiguous in frequency.

    ``departure_hz`` replaces the built-in parabola with a callable of ``t``
    returning a frequency departure in Hz, for a measured synthesiser
    characteristic.  When it is given, ``nonlinearity_ppm`` is ignored and the
    caller owns the whole departure.
    """
    validate_schedule(sweep)
    tt = np.asarray(t, dtype=float)
    if sweep_law.is_stepped(sweep):
        if departure_hz is not None:
            base = sweep_law.frequency_hz(
                sweep if sweep.nonlinearity_ppm == 0.0 else _without_nonlinearity(sweep), tt
            )
            return base + np.asarray(departure_hz(tt), dtype=float)
        return sweep_law.frequency_hz(sweep, tt)
    duration = sweep_duration_s(sweep)
    k = float(sweep.k_f_hz_per_s)
    direction = int(sweep.direction)
    f0 = float(sweep.f_start_hz) if direction > 0 else float(sweep.f_stop_hz)

    ideal = f0 + direction * k * tt
    if departure_hz is not None:
        return ideal + np.asarray(departure_hz(tt), dtype=float)
    eps = float(sweep.nonlinearity_ppm) * 1.0e-6
    if eps == 0.0:
        return ideal
    return ideal + direction * sweep_bandwidth_hz(sweep) * eps * _parabolic_departure(tt, duration)


def sweep_phase_rad(
    sweep: SweepSchedule,
    t: np.ndarray | float,
    *,
    departure_phase_rad: Callable[[np.ndarray], np.ndarray] | None = None,
) -> np.ndarray:
    """Accumulated phase at times ``t``, radians, taken as an exact integral.

    ``phi(t) = 2 pi [ f0 t + d K t^2 / 2 + d B eps P(t) ]`` with ``P`` the
    integral of the parabolic departure.
    """
    validate_schedule(sweep)
    tt = np.asarray(t, dtype=float)
    if sweep_law.is_stepped(sweep):
        if departure_phase_rad is not None:
            base = sweep_law.phase_rad(_without_nonlinearity(sweep), tt)
            return base + np.asarray(departure_phase_rad(tt), dtype=float)
        return sweep_law.phase_rad(sweep, tt)
    duration = sweep_duration_s(sweep)
    k = float(sweep.k_f_hz_per_s)
    direction = int(sweep.direction)
    f0 = float(sweep.f_start_hz) if direction > 0 else float(sweep.f_stop_hz)

    phase = 2.0 * np.pi * (f0 * tt + direction * k * tt**2 / 2.0)
    if departure_phase_rad is not None:
        return phase + np.asarray(departure_phase_rad(tt), dtype=float)
    eps = float(sweep.nonlinearity_ppm) * 1.0e-6
    if eps == 0.0:
        return phase
    return phase + 2.0 * np.pi * direction * sweep_bandwidth_hz(sweep) * eps * (
        _parabolic_departure_integral(tt, duration)
    )


def generate_sweep(
    sweep: SweepSchedule,
    fs_hz: float,
    n_samples: int | None = None,
    *,
    amplitude: float = 1.0,
    departure_hz: Callable[[np.ndarray], np.ndarray] | None = None,
    departure_phase_rad: Callable[[np.ndarray], np.ndarray] | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """One sweep as complex samples, with its time grid.

    Returns ``(t, samples)``.  The samples are the analytic signal
    ``A exp(i phi(t))``, not a real passband waveform: the instrument works at
    complex baseband and carrying the analytic form avoids generating a spectrum
    at the sounding frequency only to throw half of it away.  ``amplitude`` is in
    units of square root of watts, so ``abs(samples)**2`` is power in watts,
    which is the convention :mod:`tss.l2_instrument.baseline` uses throughout.

    The phase comes from :func:`sweep_phase_rad`, so a caller that needs a
    de-chirp reference calls this once and conjugates it rather than building a
    second waveform.  That is what makes the single-reference architecture of
    INS-21 true in the simulator and not only in the block diagram.
    """
    t = sweep_time_grid(sweep, fs_hz, n_samples)
    phase = sweep_phase_rad(
        sweep, t, departure_phase_rad=departure_phase_rad
    )
    if departure_hz is not None and departure_phase_rad is None:
        # A frequency departure given without its phase integral cannot be
        # turned into phase exactly, so it is refused rather than approximated.
        raise ValueError(
            "departure_hz changes the frequency law but generate_sweep needs the "
            "matching phase; pass departure_phase_rad as well"
        )
    return t, float(amplitude) * np.exp(1j * phase)


def _without_nonlinearity(sweep: SweepSchedule) -> SweepSchedule:
    """The same schedule with the built-in departure switched off."""
    from dataclasses import replace

    return replace(sweep, nonlinearity_ppm=0.0)


def beat_frequency_hz(group_delay_s: np.ndarray | float, sweep: SweepSchedule) -> np.ndarray:
    """De-chirped beat frequency for a two-way group delay, Hz.

    ``f_b = K_f * tau``.  Equivalently ``2 K_f R / c`` for a geometric range,
    which is the form :func:`tss.constants.beat_frequency` takes.  Both are here
    because an echo carries a delay and a link budget carries a range, and
    converting one to the other at the call site is how a factor of two gets
    lost.

    For a stepped schedule this uses ``k_f_hz_per_s``, the peak rate, and so
    gives the largest beat any step produces.  The beat within a given step is
    ``K_i * tau`` with ``K_i`` from :func:`tss.sweep_law.rate_hz_per_s`.
    """
    return float(sweep.k_f_hz_per_s) * np.asarray(group_delay_s, dtype=float)


def schedule_from_config(cfg: Mapping[str, Any]) -> SweepSchedule:
    """Build a :class:`~tss.interfaces.SweepSchedule` from the ``sweep:`` block.

    The keys are the ones ``config/default.yaml`` uses and there is no
    translation layer, deliberately: a configuration key that does not match the
    field it sets is a key that will eventually be set to the wrong thing.

    A block with ``step_dwell_s`` builds the stepped A1 law, and its
    ``k_f_hz_per_s`` is the peak step rate computed from that law.  A stated
    ``k_f_hz_per_s`` is checked against it to 1%, which admits the rounded
    5.6 MHz/s of Rev G and refuses a real disagreement.  A ``sweep_period_s`` of zero or
    absent means the active duration.
    """
    if float(cfg.get("step_dwell_s", 0.0) or 0.0) > 0.0:
        schedule = sweep_law.stepped_schedule(
            float(cfg["f_start_hz"]),
            float(cfg["f_stop_hz"]),
            float(cfg["step_dwell_s"]),
            step_fraction=float(cfg.get("step_fraction", 0.05)),
            step_cap_hz=float(cfg.get("step_cap_hz", 150.0e3)),
            sweep_period_s=float(cfg.get("sweep_period_s", 0.0) or 0.0),
            direction=int(cfg.get("direction", 1)),
            nonlinearity_ppm=float(cfg.get("nonlinearity_ppm", 0.0)),
            narrow_lo_hz=float(cfg.get("narrow_lo_hz", 0.0) or 0.0),
            narrow_hi_hz=float(cfg.get("narrow_hi_hz", 0.0) or 0.0),
            narrow_cap_hz=float(cfg.get("narrow_cap_hz", 0.0) or 0.0),
        )
        stated = cfg.get("k_f_hz_per_s")
        if stated is not None and abs(float(stated) - schedule.k_f_hz_per_s) > (
            0.01 * schedule.k_f_hz_per_s
        ):
            raise ValueError(
                f"sweep block states k_f_hz_per_s={float(stated):.6g} but its step law "
                f"peaks at {schedule.k_f_hz_per_s:.6g} Hz/s; omit k_f_hz_per_s for a "
                "stepped sweep or make the two agree"
            )
        validate_schedule(schedule)
        return schedule
    schedule = SweepSchedule(
        f_start_hz=float(cfg["f_start_hz"]),
        f_stop_hz=float(cfg["f_stop_hz"]),
        k_f_hz_per_s=float(cfg["k_f_hz_per_s"]),
        sweep_period_s=float(cfg["sweep_period_s"]),
        direction=int(cfg.get("direction", 1)),
        nonlinearity_ppm=float(cfg.get("nonlinearity_ppm", 0.0)),
    )
    validate_schedule(schedule)
    return schedule
